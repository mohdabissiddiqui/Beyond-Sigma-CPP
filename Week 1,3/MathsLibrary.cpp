#include <iostream>
using namespace std;

#include <cmath>

int main() {

    // We have to use this #include <cmath> to access maths library
    
    cout << max(2,3) << endl;
    cout << min(2,3) << endl;
    cout << pow(2,3) << endl;
    cout << ceil(2.5) << endl;
    cout << floor(2.3) << endl;
    cout << abs(-3) << endl;
    
    return 0;
}